let nivelAtual = 0;

let perguntaAtual = 0;

let pontos = 0;

let respondeu = false;

let pontosPorNivel = [0, 0, 0];


const perguntaElemento =
    document.getElementById("pergunta");

const opcoesElemento =
    document.getElementById("opcoes");

const contadorElemento =
    document.getElementById("contador");

const pontuacaoElemento =
    document.getElementById("pontuacao");

const progressoElemento =
    document.getElementById("progresso");

const botaoProximo =
    document.getElementById("botaoProximo");

const nivelElemento =
    document.getElementById("nivel");


/*
=================================
MOSTRAR PERGUNTA
=================================
*/

function mostrarPergunta() {

    respondeu = false;

    botaoProximo.disabled = true;

    const nivel = niveis[nivelAtual];

    const pergunta = nivel.perguntas[perguntaAtual];


    nivelElemento.textContent =
        nivel.nome;


    perguntaElemento.textContent =
        pergunta.pergunta;


    contadorElemento.textContent =
        "Pergunta " +
        (perguntaAtual + 1) +
        " de " +
        nivel.perguntas.length;


    pontuacaoElemento.textContent =
        "Pontos: " + pontos;


    progressoElemento.style.width =
        (
            (perguntaAtual + 1) /
            nivel.perguntas.length *
            100
        ) + "%";


    opcoesElemento.innerHTML = "";


    pergunta.opcoes.forEach(
        function(opcao, indice) {

            const botao =
                document.createElement("button");


            botao.textContent =
                opcao;


            botao.className =
                "opcao";


            botao.addEventListener(
                "click",
                function() {

                    verificarResposta(
                        indice,
                        botao
                    );

                }
            );


            opcoesElemento.appendChild(
                botao
            );

        }
    );
}


/*
=================================
VERIFICAR RESPOSTA
=================================
*/

function verificarResposta(
    indice,
    botao
) {

    if (respondeu) {
        return;
    }


    respondeu = true;


    const correta =
        niveis[nivelAtual]
        .perguntas[perguntaAtual]
        .correta;


    const botoes =
        document.querySelectorAll(".opcao");


    botoes.forEach(
        function(botao) {

            botao.disabled = true;

        }
    );


    if (indice === correta) {

        botao.classList.add(
            "correta"
        );


        pontos++;


        pontosPorNivel[nivelAtual]++;


        pontuacaoElemento.textContent =
            "Pontos: " + pontos;

    } else {

        botao.classList.add(
            "errada"
        );


        botoes[correta]
            .classList.add(
                "correta"
            );

    }


    botaoProximo.disabled = false;
}


/*
=================================
PRÓXIMA PERGUNTA
=================================
*/

botaoProximo.addEventListener(
    "click",
    function() {

        perguntaAtual++;


        const quantidade =
            niveis[nivelAtual]
            .perguntas.length;


        if (
            perguntaAtual <
            quantidade
        ) {

            mostrarPergunta();

        } else {

            terminarNivel();

        }

    }
);


/*
=================================
TERMINAR NÍVEL
=================================
*/

function terminarNivel() {

    document
        .getElementById("quiz")
        .classList.add("escondido");


    if (
        nivelAtual <
        niveis.length - 1
    ) {

        mostrarTransicao();

    } else {

        mostrarResultado();

    }
}


/*
=================================
TELA ENTRE OS NÍVEIS
=================================
*/

function mostrarTransicao() {

    const proximoNivel =
        niveis[nivelAtual + 1];


    document
        .getElementById("transicao")
        .classList.remove(
            "escondido"
        );


    document
        .getElementById("tituloTransicao")
        .textContent =
        "🎉 " +
        niveis[nivelAtual].nome +
        " concluído!";


    document
        .getElementById("textoTransicao")
        .textContent =
        "Você fez " +
        pontosPorNivel[nivelAtual] +
        " de 10 pontos. " +
        "O próximo desafio é " +
        proximoNivel.nome +
        "!";
}


/*
=================================
PRÓXIMO NÍVEL
=================================
*/

document
    .getElementById("botaoNivel")
    .addEventListener(
        "click",
        function() {

            nivelAtual++;

            perguntaAtual = 0;


            document
                .getElementById("transicao")
                .classList.add(
                    "escondido"
                );


            document
                .getElementById("quiz")
                .classList.remove(
                    "escondido"
                );


            mostrarPergunta();

        }
    );


/*
=================================
RESULTADO FINAL
=================================
*/

function mostrarResultado() {

    document
        .getElementById("resultado")
        .classList.remove(
            "escondido"
        );


    document
        .getElementById("pontuacaoFinal")
        .textContent =
        "🏆 " +
        pontos +
        " / 30 pontos";


    document
        .getElementById("resultadoFacil")
        .textContent =
        "🟢 Fácil: " +
        pontosPorNivel[0] +
        " / 10";


    document
        .getElementById("resultadoMedio")
        .textContent =
        "🟡 Médio: " +
        pontosPorNivel[1] +
        " / 10";


    document
        .getElementById("resultadoDificil")
        .textContent =
        "🔴 Difícil: " +
        pontosPorNivel[2] +
        " / 10";


    let mensagem;


    if (pontos >= 27) {

        mensagem =
            "🏆 INCRÍVEL! Você é um verdadeiro mestre!";

    } else if (pontos >= 23) {

        mensagem =
            "🌟 Excelente! Seu conhecimento é muito bom!";

    } else if (pontos >= 18) {

        mensagem =
            "👏 Muito bom! Você teve um ótimo desempenho!";

    } else if (pontos >= 12) {

        mensagem =
            "😊 Bom trabalho! Continue estudando!";

    } else {

        mensagem =
            "📚 Continue estudando e tente novamente!";

    }


    document
        .getElementById("mensagemFinal")
        .textContent =
        mensagem;
}


/*
=================================
REINICIAR
=================================
*/

document
    .getElementById("botaoReiniciar")
    .addEventListener(
        "click",
        function() {

            nivelAtual = 0;

            perguntaAtual = 0;

            pontos = 0;

            pontosPorNivel = [
                0,
                0,
                0
            ];


            document
                .getElementById("resultado")
                .classList.add(
                    "escondido"
                );


            document
                .getElementById("quiz")
                .classList.remove(
                    "escondido"
                );


            mostrarPergunta();

        }
    );


/*
=================================
INICIAR
=================================
*/

mostrarPergunta();